#!/usr/bin/env python3
"""Deterministically builds schema/pagespec.schema.json (draft-07) from the contracts.

Sources of truth: sections/*.json (content + motion contracts), templates/templates.json,
assets/asset-roles.json, tokens/llm/motion-patterns.json.

  python3 schema/build_schema.py          # (re)write pagespec.schema.json
  python3 schema/build_schema.py --check  # exit 1 if the committed schema has drifted

verify_all.py imports build() and diffs it against the committed file.
"""
import glob
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SCHEMA_PATH = os.path.join(ROOT, "schema", "pagespec.schema.json")
URL_PATTERN = r"^(/[^\s]*|#[^\s]*|https://[^\s]+|mailto:[^\s]+)$"


def _load(rel):
    with open(os.path.join(ROOT, rel), encoding="utf-8") as fh:
        return json.load(fh)


def field_schema(f, roles_doc):
    t = f["type"]
    if t == "text":
        return {"type": "string", "minLength": 1}
    if t == "url":
        return {"type": "string", "pattern": URL_PATTERN}
    if t == "pattern":
        return {"type": "string", "pattern": f["pattern"]}
    if t == "integer":
        return {"type": "integer", "minimum": f["minimum"], "maximum": f["maximum"]}
    if t == "boolean":
        return {"type": "boolean"}
    if t == "enum":
        return {"enum": list(f["values"])}
    if t == "media":
        return {"type": "object", "additionalProperties": False, "required": ["assetRole", "source"],
                "properties": {"assetRole": {"enum": sorted(f["roles"])},
                               "source": {"enum": roles_doc["mediaSources"]},
                               "alt": {"type": "string", "maxLength": 140}}}
    if t == "endpoint":
        return {"type": "object", "additionalProperties": False, "required": ["assetRole", "target"],
                "properties": {"assetRole": {"enum": sorted(f["roles"])},
                               "target": {"enum": roles_doc["endpointTargets"]}}}
    if t == "list":
        return {"type": "array", "minItems": f["minItems"], "maxItems": f["maxItems"],
                "items": field_schema(f["items"], roles_doc)}
    if t == "object":
        return fields_schema(f["fields"], roles_doc)
    raise ValueError(f"unknown field type {t}")


def fields_schema(fields, roles_doc):
    return {"type": "object", "additionalProperties": False,
            "required": [k for k, v in fields.items() if v.get("required", True)],
            "properties": {k: field_schema(v, roles_doc) for k, v in fields.items()}}


def build():
    sections = {}
    for p in sorted(glob.glob(os.path.join(ROOT, "sections", "*.json"))):
        with open(p, encoding="utf-8") as fh:
            d = json.load(fh)
        sections[d["id"]] = d
    roles_doc = _load("assets/asset-roles.json")
    templates = _load("templates/templates.json")["templates"]
    mp = _load("tokens/llm/motion-patterns.json")
    patterns = sorted(mp["patterns"])
    fallbacks = sorted(mp["reducedMotionFallbacks"])
    branches = []
    for sid in sorted(sections):
        s = sections[sid]
        m = s["motion"]
        allowed = sorted(set(m["allowedPatterns"]))
        branches.append({
            "if": {"properties": {"section": {"const": sid}}, "required": ["section"]},
            "then": {"properties": {
                "variant": {"enum": sorted(s["variants"])},
                "content": fields_schema(s["content"], roles_doc),
                "motion": {"properties": {"patterns": {"items": {"enum": allowed}},
                                          "reducedMotionFallback": {"const": m["reducedMotionFallback"]}}},
            }},
        })
    return {
        "$schema": "http://json-schema.org/draft-07/schema#",
        "$id": "pagespec.schema.json",
        "title": "Conductor clone PageSpec",
        "description": "Generated by schema/build_schema.py from the section contracts. Structural rules (template cross-reference, graph rules, maxWords, asset-role pins) live in semantic_validate.py.",
        "type": "object",
        "additionalProperties": False,
        "required": ["pageSpecVersion", "template", "route", "nodes"],
        "properties": {
            "pageSpecVersion": {"const": "1.0.0"},
            "template": {"enum": sorted(templates)},
            "route": {"type": "string", "pattern": r"^/[A-Za-z0-9/._-]*$"},
            "nodes": {"type": "array", "minItems": 1, "items": {"$ref": "#/definitions/node"}},
        },
        "definitions": {
            "motion": {
                "type": "object", "additionalProperties": False,
                "required": ["patterns", "reducedMotionFallback"],
                "properties": {
                    "patterns": {"type": "array", "uniqueItems": True, "items": {"enum": patterns}},
                    "reducedMotionFallback": {"enum": fallbacks},
                },
            },
            "node": {
                "type": "object", "additionalProperties": False,
                "required": ["type", "section", "variant", "content", "motion"],
                "properties": {
                    "type": {"enum": ["section"]},
                    "section": {"enum": sorted(sections)},
                    "variant": {"type": "string"},
                    "content": {"type": "object"},
                    "motion": {"$ref": "#/definitions/motion"},
                },
                "allOf": branches,
            },
        },
    }


def dumps(obj):
    return json.dumps(obj, indent=2, ensure_ascii=False) + "\n"


if __name__ == "__main__":
    text = dumps(build())
    if "--check" in sys.argv:
        with open(SCHEMA_PATH, encoding="utf-8") as fh:
            same = fh.read() == text
        print("schema up to date" if same else "SCHEMA DRIFT: rerun schema/build_schema.py")
        sys.exit(0 if same else 1)
    with open(SCHEMA_PATH, "w", encoding="utf-8") as fh:
        fh.write(text)
    print("wrote", os.path.relpath(SCHEMA_PATH, ROOT))
